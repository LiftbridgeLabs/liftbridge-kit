import Foundation
import LiftbridgeThemes

// Writes the Android library's theme catalog from the Swift one, so both
// platforms show the same themes in the same colors. Run from the repo root
// after any change to the themes:
//
//   swift run KotlinCatalog
//
// It also writes the Swift results of Black mode and of a frame built from a
// swatch, which the Android tests compare their own color math against.

let root = "android/themes/src"
let header = "// Generated by `swift run KotlinCatalog` from the Swift catalog. Don't edit by hand.\n"

func hex(_ rgb: RGB) -> String { "0x" + rgb.hex }
func shade(_ shade: Shade) -> String { "Shade(\(hex(shade.light)), \(hex(shade.dark)))" }

func palette(_ p: Palette, indent: String) -> String {
    let roles: [(String, Shade)] = [
        ("accent", p.accent), ("onAccent", p.onAccent), ("canvas", p.canvas), ("canvasEnd", p.canvasEnd),
        ("card", p.card), ("chip", p.chip), ("hairline", p.hairline), ("ink", p.ink), ("muted", p.muted),
        ("success", p.success), ("chrome", p.chrome), ("chromeEnd", p.chromeEnd), ("onChrome", p.onChrome),
        ("selection", p.selection), ("onSelection", p.onSelection),
    ]
    let lines = roles.map { "\(indent)    \($0.0) = \(shade($0.1))," }.joined(separator: "\n")
    return "Palette(\n\(lines)\n\(indent))"
}

func swatch(_ s: Swatch) -> String {
    "Swatch.of(\(hex(s.light[0])) to \(hex(s.light[1])), \(hex(s.dark[0])) to \(hex(s.dark[1])))"
}

func kotlinString(_ text: String) -> String {
    "\"" + text.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"")
        .replacingOccurrences(of: "$", with: "\\$") + "\""
}

func functionName(_ id: String) -> String {
    let parts = id.split(separator: "-")
    return "group" + parts.map { $0.prefix(1).uppercased() + $0.dropFirst() }.joined()
}

// The catalog: one function per group keeps each method small for the JVM.
var catalog = header + """

package com.liftbridgelabs.themes

/** Every shared theme group, in picker order, with each theme's finished colors. */
internal object GeneratedCatalog {
    val groups: List<ThemeGroup> by lazy {
        listOf(\(ThemeGroup.shared.map { functionName($0.id) + "()" }.joined(separator: ", ")))
    }

"""
for group in ThemeGroup.shared {
    let season = group.season.map { "Season(\($0.start.month), \($0.start.day), \($0.end.month), \($0.end.day))" } ?? "null"
    let themes = group.themes.map { theme in
        """
                Theme(
                    id = \(kotlinString(theme.id)),
                    name = \(kotlinString(theme.name)),
                    swatch = \(swatch(theme.swatch)),
                    palette = \(palette(theme.palette, indent: "            ")),
                )
        """
    }.joined(separator: ",\n")
    catalog += """
        private fun \(functionName(group.id))() = ThemeGroup(
            id = \(kotlinString(group.id)),
            title = \(kotlinString(group.title)),
            season = \(season),
            themes = listOf(
    \(themes),
            ),
        )


    """
}
catalog = catalog.trimmingCharacters(in: .newlines) + "\n}\n"

// What Swift computes for Black mode and for frames, for the Android tests.
let sampleHouse = Theme(id: "house", name: "House", swatch: Swatch((0xF0A070, 0xB4410F), dark: (0x4A1E0C, 0xB4410F)),
                        palette: Palette(
                            accent: Shade(0xB4410F, 0xF08A4B), onAccent: Shade(0xFFFFFF, 0x16120F),
                            canvas: Shade(0xFAF7F2, 0x16120F), card: Shade(0xFFFFFF, 0x241E19),
                            chip: Shade(0xF1EADF, 0x2C251F), hairline: Shade(0xE6DED2, 0x3A322A),
                            ink: Shade(0x1F1B16, 0xF6EFE6), muted: Shade(0x6B6259, 0xB9AFA3),
                            success: Shade(0x3F6212, 0x9BC26A), canvasEnd: Shade(0xF4EADC, 0x1E140D)))
var expected = header + """

