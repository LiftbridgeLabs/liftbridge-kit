"""

let package = "\(root)/main/kotlin/com/liftbridgelabs/themes"
let tests = "\(root)/test/kotlin/com/liftbridgelabs/themes"
try FileManager.default.createDirectory(atPath: package, withIntermediateDirectories: true)
try FileManager.default.createDirectory(atPath: tests, withIntermediateDirectories: true)
try catalog.write(toFile: "\(package)/GeneratedCatalog.kt", atomically: true, encoding: .utf8)
try expected.write(toFile: "\(tests)/SwiftResults.kt", atomically: true, encoding: .utf8)
print("\(package)/GeneratedCatalog.kt")
