    }

    /** A house palette given without a frame, as an app passes one. */
    val house = \(palette(sampleHouse.palette, indent: "    "))
    val houseSwatch = \(swatch(sampleHouse.swatch))
    val houseBlack = \(palette(sampleHouse.black.palette, indent: "    "))
    val houseFramed = \(palette(sampleHouse.palette.withFrame(from: sampleHouse.swatch), indent: "    "))
